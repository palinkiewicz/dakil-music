#!/usr/bin/env python3
"""Generate the app's preset color schemes from seed colors.

Every role of each light/dark ColorScheme (surface containers, fixed roles, ...) is derived with
Google's Material Color Utilities (Python port `materialyoucolor`, TonalSpot variant unless VARIANTS says otherwise), the
same algorithm Android uses for wallpaper-based dynamic color. The result is baked into
app/src/main/java/pl/dakil/music/ui/theme/ColorSchemes.kt so the app carries no runtime
dependency for it.

Usage (needs `pip install materialyoucolor`, e.g. in a throwaway venv):
    python3 -I tools/generate-schemes.py
"""
import pathlib

from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors
from materialyoucolor.hct.hct import Hct
from materialyoucolor.scheme.scheme_content import SchemeContent
from materialyoucolor.scheme.scheme_tonal_spot import SchemeTonalSpot

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/java/pl/dakil/music/ui/theme/ColorSchemes.kt"

# Kotlin name prefix -> seed (ARGB). Seeds are the presets' original light primaries.
SEEDS = {
    "DakilsMusic": 0xFFC00069,
    "Ocean": 0xFF0061A4,
    "Lavender": 0xFF6750A4,
    "Sunset": 0xFF8C5000,
    "Rose": 0xFF984061,
    "Teal": 0xFF006A60,
}

# Compose ColorScheme parameter -> MaterialDynamicColors attribute.
ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
    "surfaceTint", "inverseSurface", "inverseOnSurface",
    "error", "onError", "errorContainer", "onErrorContainer",
    "outline", "outlineVariant", "scrim",
    "surfaceBright", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
    "surfaceContainerLow", "surfaceContainerLowest", "surfaceDim",
    "primaryFixed", "primaryFixedDim", "onPrimaryFixed", "onPrimaryFixedVariant",
    "secondaryFixed", "secondaryFixedDim", "onSecondaryFixed", "onSecondaryFixedVariant",
    "tertiaryFixed", "tertiaryFixedDim", "onTertiaryFixed", "onTertiaryFixedVariant",
]


# Presets built with a variant other than TonalSpot. The brand keeps its vivid pink: Content puts the
# seed itself in primaryContainer, where TonalSpot would mute it to a dusty rose.
VARIANTS = {
    "DakilsMusic": SchemeContent,
}


# Presets whose secondary and tertiary roles still come from TonalSpot: Content's are as loud as
# its primary (tertiary even turns error-red), so tonal buttons and chips would all compete.
CALM_SECONDARY = {"DakilsMusic"}


def scheme_block(name: str, seed: int, dark: bool) -> str:
    scheme = VARIANTS.get(name, SchemeTonalSpot)(Hct.from_int(seed), dark, 0.0)
    calm = SchemeTonalSpot(Hct.from_int(seed), dark, 0.0)
    builder = "darkColorScheme" if dark else "lightColorScheme"
    lines = [f"internal val {name}{'Dark' if dark else 'Light'} = {builder}("]
    for role in ROLES:
        source = calm if name in CALM_SECONDARY and ("econdary" in role or "ertiary" in role) else scheme
        argb = getattr(MaterialDynamicColors, role).get_argb(source) & 0xFFFFFFFF
        lines.append(f"    {role} = Color(0x{argb:08X}),")
    lines.append(")")
    return "\n".join(lines)


def main() -> None:
    blocks = []
    for name, seed in SEEDS.items():
        blocks.append(f"// {name}: seed #{seed & 0xFFFFFF:06X}")
        blocks.append(scheme_block(name, seed, dark=False))
        blocks.append(scheme_block(name, seed, dark=True))
    OUT.write_text(
        "// GENERATED by tools/generate-schemes.py — do not edit by hand.\n"
        "package pl.dakil.music.ui.theme\n\n"
        "import androidx.compose.material3.darkColorScheme\n"
        "import androidx.compose.material3.lightColorScheme\n"
        "import androidx.compose.ui.graphics.Color\n\n"
        + "\n\n".join(blocks)
        + "\n"
    )
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
