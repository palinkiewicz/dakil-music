#!/usr/bin/env python3
"""Fetch the Material Symbols Rounded (outline + filled) used by Music.

Reads tools/icons.txt, writes Android vector drawables into app/src/main/res/drawable
(sym_<name>.xml and sym_<name>_fill.xml) and generates the typed Kotlin catalog AppSymbols.kt.
Material Symbols are Apache-2.0 licensed (https://github.com/google/material-design-icons).

Usage: python3 -I tools/fetch-icons.py
"""
import concurrent.futures
import pathlib
import re
import sys
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / "tools" / "icons.txt"
RES = ROOT / "app/src/main/res/drawable"
KT = ROOT / "app/src/main/java/pl/dakil/music/ui/designsystem/icon/AppSymbols.kt"
URL = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/android/{n}/materialsymbolsrounded/{f}"

# Directional glyphs that must flip in right-to-left layouts.
MIRRORED = {
    "arrow_back", "chevron_right", "undo", "redo", "send", "open_in_new", "wrap_text", "sort",
    "queue_music", "playlist_add", "playlist_play", "playlist_remove", "volume_up", "volume_off", "trending_up",
}


def fetch(name: str, filled: bool) -> str | None:
    file = f"{name}_fill1_24px.xml" if filled else f"{name}_24px.xml"
    try:
        with urllib.request.urlopen(URL.format(n=name, f=file), timeout=30) as response:
            return response.read().decode("utf-8")
    except urllib.error.HTTPError:
        return None


def clean(xml: str, mirrored: bool) -> str:
    # Tint comes from Compose's LocalContentColor; a theme-attr tint only gets in the way.
    xml = re.sub(r'\s*android:tint="[^"]*"', "", xml)
    xml = re.sub(r'\s*android:autoMirrored="[^"]*"', "", xml)
    if mirrored:
        xml = xml.replace("<vector ", '<vector android:autoMirrored="true" ', 1)
    return xml


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def main() -> int:
    names = []
    for line in LIST.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and line not in names:
            names.append(line)

    RES.mkdir(parents=True, exist_ok=True)
    for old in RES.glob("sym_*.xml"):
        old.unlink()

    def download(name):
        return name, fetch(name, filled=False), fetch(name, filled=True)

    available = []
    missing = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=16) as pool:
        for name, outline, filled in pool.map(download, names):
            if outline is None:
                missing.append(name)
                continue
            mirrored = name in MIRRORED
            (RES / f"sym_{name}.xml").write_text(clean(outline, mirrored))
            (RES / f"sym_{name}_fill.xml").write_text(clean(filled or outline, mirrored))
            available.append(name)

    lines = [
        "// Generated by tools/fetch-icons.py from tools/icons.txt. Do not edit by hand.",
        "package pl.dakil.music.ui.designsystem.icon",
        "",
        "import pl.dakil.music.R",
        "",
        "object AppSymbols {",
        *[
            f"    val {camel(n)} = AppSymbol(R.drawable.sym_{n}, R.drawable.sym_{n}_fill)"
            for n in available
        ],
        "}",
        "",
    ]
    KT.parent.mkdir(parents=True, exist_ok=True)
    KT.write_text("\n".join(lines))
    print(f"{len(available)} symbols")
    for name in missing:
        print(f"missing: {name}", file=sys.stderr)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
